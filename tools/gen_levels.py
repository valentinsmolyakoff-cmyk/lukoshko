def seq_round(symbols, period_len, opts_extra, q='Продолжи узор'):
    """Строит узор и ВЫЧИСЛЯЕТ правильный ответ — без ручных ошибок."""
    pat = list(symbols[:period_len])
    while len(pat) < 5: pat = pat + list(symbols[:period_len])
    pat = pat[:5]
    p = period_len
    expected = pat[len(pat) % p]
    opts = [expected] + [s for s in opts_extra if s != expected][:2]
    assert len(opts) == 3 and len(set(opts)) == 3, (symbols, opts)
    return {"k":"seq","q":q,"pattern":pat,"opts":opts,"ans":expected}


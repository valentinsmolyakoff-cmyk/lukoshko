def q(x):
    """строка в одинарных кавычках для читаемого JS"""
    return "'" + str(x).replace("\\", "\\\\").replace("'", "\\'") + "'"

def arr(a):
    return "[" + ",".join(q(x) for x in a) + "]"

def objnum(d):
    parts = []
    for k, v in d.items():
        if isinstance(v, bool): v = "true" if v else "false"
        elif isinstance(v, str): v = q(v)
        parts.append(f"{k}:{v}")
    return "{" + ",".join(parts) + "}"

def round_js(r):
    k = r['k']
    if k == 'catch':
        extra = dict(r.get('opts') or {})
        for kk, vv in r.items():
            if kk in ('k','q','good','bad','need','opts'): continue
            extra[kk] = vv
        return f"  c({q(r['q'])}, {arr(r['good'])}, {arr(r['bad'])}, {r['need']}, {objnum(extra)})"
    if k == 'word':
        extra = {kk: vv for kk, vv in r.items() if kk not in ('k','q','w')}
        tail = (", " + objnum(extra)[1:-1]) if extra else ""
        return f"  {{k:'word', q:{q(r['q'])}, w:{q(r['w'])}{tail}}}"
    if k == 'sort':
        bins = "[" + ",".join("{e:%s,match:%s}" % (q(b['e']), arr(b['match'])) for b in r['bins']) + "]"
        return f"  {{k:'sort', q:{q(r['q'])}, bins:{bins}, items:{arr(r['items'])}, need:{r['need']}, rate:{r['rate']}}}"
    if k == 'mem':
        return f"  {{k:'mem', q:{q(r['q'])}, set:{arr(r['set'])}}}"
    if k == 'odd':
        return f"  {{k:'odd', q:{q(r['q'])}, items:{arr(r['items'])}, ans:{r['ans']}}}"
    if k == 'seq':
        return f"  {{k:'seq', q:{q(r['q'])}, pattern:{arr(r['pattern'])}, opts:{arr(r['opts'])}, ans:{q(r['ans'])}}}"
    if k == 'choice':
        return f"  {{k:'choice', q:{q(r['q'])}, opts:{arr(r['opts'])}, ans:{q(r['ans'])}}}"
    if k == 'diff':
        return f"  {{k:'diff', q:{q(r['q'])}, set:{arr(r['set'])}, cols:{r['cols']}, rows:{r['rows']}}}"
    if k == 'dots':
        return f"  {{k:'dots', q:{q(r['q'])}, count:{r['count']}}}"
    if k == 'maze':
        return f"  {{k:'maze', q:{q(r['q'])}, size:{r['size']}}}"
    if k == 'rhythm':
        return f"  {{k:'rhythm', q:{q(r['q'])}, good:{arr(r['good'])}, bad:{arr(r['bad'])}, need:{r['need']}, speed:{r['speed']}}}"
    raise ValueError(k)

def level_js(l):
    body = ",\n".join(round_js(r) for r in l['r'])
    return f"{{n:{l['n']}, w:{l['w']}, t:{q(l['t'])}, r:[\n{body}]}}"

